"""Real lazy SDK services for the isolated, owner-authorized V2 controller.

An operator-owned immutable grant binds one job, quote, source, cap and actor.
It cannot be supplied as stage_options or generated by the provider factory.
SDK retries are disabled; costs come from tokens/LRO billed-duration evidence,
not an estimate. Final billing exports remain a separate reconciliation.
"""
import hashlib
import hmac
import json
import os
from pathlib import Path
from types import SimpleNamespace

from app.jobs.golden_v2_ledger import GoldenV2Ledger, V2Conflict
from app.pipeline.golden_v2_pricing import (assert_current, gemini_usage_cents,
                                          chirp_cents, chirp_operation_cents,
                                          INPUT_TOKEN_CAP, OUTPUT_TOKEN_CAP)
from app.pipeline.golden_v2_quote_intake import wire
from app.providers.golden_v2_audio_staging import file_sha256
from app.providers.golden_v2_immutable import store_immutable_bytes
