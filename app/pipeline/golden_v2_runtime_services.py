def _secret():
    secret = os.environ.get('COURSE_TRANSCRIPT_V2_GRANT_SECRET','')
    if len(secret) < 32:
        raise V2Conflict('independent runtime grant verification not configured')
    return secret.encode()


def signed_grant(payload):
    return {'grant':payload,'signature':hmac.new(_secret(),wire(payload).encode(),hashlib.sha256).hexdigest()}


def verify_job_grant(*, root, snapshot):
    job = root/'jobs'/snapshot['job_id']
    quote_path = job/'trusted-quote.json'; grant_path = job/'owner-paid-grant.json'
    if quote_path.is_symlink() or grant_path.is_symlink():
        raise V2Conflict('immutable owner grant required')
    quote = json.loads(quote_path.read_text()); envelope = json.loads(grant_path.read_text())
    payload = envelope['grant']
    expected = signed_grant(payload)['signature']
    if not hmac.compare_digest(expected,envelope['signature']):
        raise V2Conflict('owner grant signature mismatch')
    if (payload['job_id'] != snapshot['job_id'] or
        payload['source_sha256'] != snapshot['source_sha256'] or
        quote['source_sha256'] != snapshot['source_sha256'] or
        payload['quote_sha256'] != file_sha256(quote_path) or
        payload['approved_cents'] > snapshot['aggregate_cap_cents'] or
        payload['approved_cents'] < quote['estimated_cents'] or
        not payload['actor'] or quote['mode'] != 'FLASH_CHIRP'):
        raise V2Conflict('owner grant source/quote/budget mismatch')
    state = GoldenV2Ledger.open_existing(root/'ledger.sqlite').status(snapshot['job_id'])
    if state['approved_cents'] != payload['approved_cents'] or state['source_sha'] != payload['source_sha256']:
        raise V2Conflict('grant disagrees with ledger approval')
    assert_current()
    return quote, payload


class BudgetedModels:
    def __init__(self, client):
        # google-genai Client.__del__ closes the HTTP transport. Retaining only
        # client.models lets the factory's local client die before dispatch.
        self._client = client
        self.models = client.models

    def generate_content(self, *, model, contents, config):
        if model != 'gemini-3.8-flash': raise V2Conflict('unexpected model')
        counted = self.models.count_tokens(model=model,contents=contents)
        tokens = getattr(counted,'total_tokens',None)
        if type(tokens) is not int or not 0 < tokens <= INPUT_TOKEN_CAP:
            raise V2Conflict('actual input token reservation exceeded')
        if isinstance(config,dict):
            output_cap = config.get('max_output_tokens')
            if output_cap is None: output_cap = OUTPUT_TOKEN_CAP
            if type(output_cap) is not int or not 0 < output_cap <= OUTPUT_TOKEN_CAP:
                raise V2Conflict('actual output token reservation exceeded')
            config = {**config,'max_output_tokens':output_cap}
        else:
            # Preserve the adapter's bounded generation identity; never raise
            # its cap or mutate the config object retained in its receipt.
            from copy import copy
            output_cap = getattr(config,'max_output_tokens',None)
            if output_cap is None: output_cap = OUTPUT_TOKEN_CAP
            if type(output_cap) is not int or not 0 < output_cap <= OUTPUT_TOKEN_CAP:
                raise V2Conflict('actual output token reservation exceeded')
            config = copy(config)
            config.max_output_tokens = output_cap
        return self.models.generate_content(model=model,contents=contents,config=config)


def _root():
    path = Path(os.environ['COURSE_TRANSCRIPT_V2_ARTIFACT_ROOT'])
    if path.is_symlink(): raise V2Conflict('isolated runtime root required')
    return path.resolve()


def _clients():
    # Independent V2 image pins google-genai 2.x. V1 dependency stays unchanged.
    from google import genai
    from google.genai import types
    from google.cloud import storage, speech_v2
    project = os.environ['GOOGLE_CLOUD_PROJECT']
    vertex = genai.Client(enterprise=True,project=project,location='global',
                         http_options=types.HttpOptions(api_version='v1',timeout=1800000,
                             retry_options=types.HttpRetryOptions(attempts=1)))
    gcs = storage.Client(project=project)
    speech = speech_v2.SpeechClient(client_options={'api_endpoint':'us-speech.googleapis.com'})
    def record_operation(row, operation):
        if operation is None or not callable(getattr(operation, 'SerializeToString', None)):
            raise V2Conflict('raw Speech operation receipt unavailable')
        path = _root()/'jobs'/row['job_id']/'golden-v2'/'chirp-submission-receipts'
        store_immutable_bytes(path/(row['request_id']+'.operation.pb'), operation.SerializeToString())
        store_immutable_bytes(path/(row['request_id']+'.json'), wire(dict(
            operation_name=operation.name, request_id=row['request_id'],
            source_sha=row['source_sha'], input_uri=row['gcs_uri'], output_uri=row['output_uri'])).encode())
    return vertex, gcs, ChirpV2Gateway(speech_client=speech,storage_client=gcs,project=project,
        project_number=os.environ.get('GOOGLE_CLOUD_PROJECT_NUMBER'), operation_recorder=record_operation)


def paid_services(snapshot):
    root = _root(); quote, grant = verify_job_grant(root=root,snapshot=snapshot)
    if snapshot['stage'] not in {'gemini_primary','chirp_independent'}:
        raise V2Conflict('third model needs a separate grant and price')
    vertex, storage, gateway = _clients()
    bucket = os.environ['GCS_BUCKET']
    common = dict(storage_client=storage,bucket_name=bucket,
                  object_prefix='golden-v2-runtime',overlap_seconds=10)

    def owner(preview):
        _, current = verify_job_grant(root=root,snapshot={**snapshot,'source_sha256':preview['source_sha256']})
        return current == grant

    def capability(preview):
        assert_current()
        # GET-only checks using the actual runtime identity. Permission probe
        # is not described as proof of model output or final invoice.
        import google.auth
        from google.auth.transport.requests import AuthorizedSession
        credentials,_ = google.auth.default(scopes=['https://www.googleapis.com/auth/cloud-platform'])
        session = AuthorizedSession(credentials)
        # Model Garden GET uses the publisher resource, not an inference URL
        # with project/location (which returns 404 even for callable models).
        model = session.get('https://aiplatform.googleapis.com/v1beta1/publishers/google/models/gemini-3.8-flash',timeout=20)
        permissions = session.get(f'https://storage.googleapis.com/storage/v1/b/{bucket}/iam/testPermissions',
                                  params={'permissions':['storage.objects.create','storage.objects.get','storage.objects.list']},timeout=20)
        expected = {'storage.objects.create','storage.objects.get','storage.objects.list'}
        return model.status_code == 200 and permissions.status_code == 200 and expected <= set(permissions.json().get('permissions',[]))

    if snapshot['stage'] == 'gemini_primary':
        options = {**common,'vertex_client':SimpleNamespace(models=BudgetedModels(vertex)),
                   'max_window_seconds':2700,'cost_accountant':gemini_usage_cents,
                   'cost_estimator':lambda manifest: quote['estimated_stage_cents']['gemini_primary']}
    else:
        options = {**common,'gateway':gateway,'max_window_seconds':900,
                   'estimate_window_cents':lambda w:chirp_cents(w['end_seconds']-w['start_seconds'])}
    return dict(verify_owner=owner,verify_capability_and_pricing=capability,stage_options=options)


def recovery_services(snapshot):
    root = _root(); verify_job_grant(root=root,snapshot=snapshot)
    _,_,gateway = _clients()
    def accountant(row):
        evidence = gateway.billing_evidence(row)
        job_dir = root/'jobs'/row['job_id']
        store_immutable_bytes(job_dir/'golden-v2'/'chirp-evidence'/row['window_id']/'billed-duration.json',wire(evidence).encode())
        return chirp_operation_cents(row, evidence['total_billed_seconds'])
    return dict(gateway=gateway,cost_accountant=accountant,max_operations=8)
